// アルカナ (§21)
//
// ── クラスとの役割分担 ──
// クラス (§12) は「役割」を選ぶ。守るのか、癒すのか、壊すのか。
// アルカナは役割ではなく **規則** を書き換える。誰が就いても同じ規則が働く。
//
// そのため、ここに数値を積む効果は置かない。効果種別は155種あり、
// 数値で差を付けようとすると必ずツリーか装備セットのどれかと被る
// （実際、最初に考えた「属性を均す」案は千変セットとほぼ同じだった）。
//
// ── 利と害が同居する ──
// タロットの正位置・逆位置の像を借りているが、**切り替わる仕掛けではない。**
// 1枚のアルカナが、大きな利と大きな害を同時に、常時もたらす。
// 「どちらが出ているか」を操作させると、遊ぶ側が管理する要素が増えるわりに
// 分かりにくくなる。常時効いているほうが、組む前に見通せる。
//
// ── 害は必ず「即時」に効くものにすること ──
// **ここを外すと代償が代償にならない。**
//
// 1ウェーブは実測で 1.0〜3.4 ラウンドしか続かない。**そして
// battle.round はウェーブごとに1へ戻る**（battle.js:1337）。
// クールダウンはこの round を見ているので、CD4の技は
// 1ラウンドで終わるウェーブでは永久に撃てない。
// （通算の totalRounds は 6〜11 ラウンド。最初ここを取り違えて
//  「戦闘は1ラウンドで終わる」と書いていた。見るラウンドが別物）
// 「クールダウンが倍になる」「毎ラウンド衰弱する」といった害は、
// 2ラウンドで終わる周回では**ただの無料の利益**になり、
// 長期戦の塔・闘技場でだけ重い。場所によって強さが極端に変わる。
//
//   ◯ 能力値を削る／手番を減らす／受けられる支援を断つ
//   ✕ クールダウン・毎ラウンドの減衰・Nラウンド後に発動
//

// アルカナ (§21)
//
// ── クラスとの役割分担 ──
// クラス (§12) は「役割」を選ぶ。守るのか、癒すのか、壊すのか。
// アルカナは役割ではなく **規則** を書き換える。誰が就いても同じ規則が働く。
//
// そのため、ここに数値を積む効果は置かない。効果種別は155種あり、
// 数値で差を付けようとすると必ずツリーか装備セットのどれかと被る
// （実際、最初に考えた「属性を均す」案は千変セットとほぼ同じだった）。
//
// ── 利と害が同居する ──
// タロットの正位置・逆位置の像を借りているが、**切り替わる仕掛けではない。**
// 1枚のアルカナが、大きな利と大きな害を同時に、常時もたらす。
// 「どちらが出ているか」を操作させると、遊ぶ側が管理する要素が増えるわりに
// 分かりにくくなる。常時効いているほうが、組む前に見通せる。
//
// ── 害は必ず「即時」に効くものにすること ──
// **ここを外すと代償が代償にならない。**
// 推奨レベルでの戦闘は実測で 1.0〜3.5 ラウンドしか続かない。
// 「クールダウンが倍になる」「毎ラウンド衰弱する」といった害は、
// 2ラウンドで終わる周回では**ただの無料の利益**になり、
// 長期戦の塔・闘技場でだけ重い。場所によって強さが極端に変わる。
//
//   ◯ 能力値を削る／手番を減らす／受けられる支援を断つ
//   ✕ クールダウン・毎ラウンドの減衰・Nラウンド後に発動
//
// ── 数値の土台 ──
// 実プレイのエンドビルド（Lv255・0凸・破壊者）を基準にしている。
//   ATK 27,434 ／ DEF 14,061 ／ HP 9,377 ／ 軽減 60.7% ／ capBreak 3.09
// テスト用の雛形ビルドは同じ Lv255 でも ATK 4,074・軽減 20.0% しかなく、
// **ATKで6.7倍、DEFで7.3倍ずれている。** 雛形で数値を決めてはいけない。

RPG.data.arcana = {

  ar_strength: {
    name: '力', reading: 'ちから', color: '#ff7a59', icon: 'stat-atk',
    flavor: '手綱を手放した者だけが、獣の速さを知る。',
    // 利と害を1行ずつ。ビルド画面はこの2つを並べて出す。
    boon: '与えるダメージが大きく上がる',
    bane: '自分が受けるとき、防御による軽減が一切働かない',
    desc: '抑えることをやめた姿。打たれ弱さと引き換えに、一撃の重さを得る。',

    // ── なぜ「防御無視される」なのか ──
    // 攻める側の guard_break（確率で防御を無視する）は既にあるが、
    // **受ける側の旗は無かった**。ここが空いている。
    //
    // しかも軽減は除算型（1 - DEF/(DEF+C)）なので、
    // 実データの 60.7% がまるごと消える。半端な代償にならない。
    //
    // ── 倍率の決め方 ──
    // 軽減60.7%を失う＝被ダメージが約2.5倍になる。
    // 釣り合わせるなら与ダメージも同程度は要るが、
    // **攻撃は選べて、防御は選べない**（殴られる回数は相手が決める）。
    // 等価だと明確に損なので、やや攻撃側へ寄せて 1.6倍から測り始める。
    //
    // ── 威力だけ足しても、育った環境では届かない (§3.2 ステップ8) ──
    // **ここが一番の落とし穴。** 終盤ビルドの素のダメージは上限の数倍に達していて、
    // 超過分は10%しか残らない。つまり「素の火力 +60%」は画面上では +13% になる。
    //
    // 実測（実プレイのセーブ・終わりなき回廊・黄昏(520)）:
    //   なし  素 5,242,885 → 表示 2,363,533（上限 2,043,605／減衰）
    //   力    素 8,388,615 → 表示 2,678,106  素は1.60倍でも **実効 1.133倍**
    //
    // 害（被ダメ2.32倍）は全額なのに、利だけが5分の1に薄まる。
    // cap_break を一緒に持たせて初めて釣り合う。
    //
    // **終盤では cap_break が唯一の実効ある火力**という、このゲームの性質そのもの。
    // 威力%を足すアルカナを新しく作るときは、必ず上限もセットで考えること。
    effects: [
      { kind: 'always_power', value: 0.60 },
      { kind: 'cap_break', value: 1.40 },
      { kind: 'defense_null', value: 1 },
    ],
  },

  ar_hanged_man: {
    name: '吊るされた男', reading: 'つるされたおとこ', color: '#6fa8dc', icon: 'stat-spd',
    flavor: '逆さに吊られた世界では、落ちることが上ることだった。',
    boon: '攻撃は必ず会心になり、威力が大きく上がる',
    bane: '毎ラウンド、手番を1つ失う',
    desc: '動かぬことを選んだ姿。振るう機会を捨てるほど、その一振りは重くなる。',

    // ── 「停止」ではなく「負債」である ──
    // 基礎手番は1人1ラウンド1回なので、素の状態では動けなくなる。
    // だが turnDebt は **再行動で返せる**。
    //   ・戦術家の「刻の号令」          … 味方が返してくれる
    //   ・ツリーの再行動 / 奇襲          … 自分で買い戻す
    //   ・段の出口（継ぎ手・§5.10）      … パーティの資源で返す
    //
    // これで代償が「詰み」ではなく「支払い方を選べる負債」になり、
    // 支援役に明確な仕事ができる。【極】ノードと同じ思想。
    //
    // ── なぜ「1ラウンドおきに動く」にしなかったか ──
    // 戦闘が1ラウンドで終わる場面では、奇数ラウンドに動く＝普通に動くのと同じで、
    // **代償がゼロになる**（実測: 光の特化型は fl_abyss を 1.0R で抜ける）。
    // 毎ラウンド -1 なら1ラウンド目から必ず支払う。
    //
    // ── 上限を押し上げるのが要 (§3.2 ステップ8) ──
    // **ここを外すと、このアルカナは強く育てるほど弱くなる。**
    //
    // 手番を減らして一撃を重くする、という取引なのに、
    // ダメージ上限の減衰は**まさに重い一撃だけを罰する**（超過分は10%しか残らない）。
    // 実測（実ビルド Lv255・capBreak 3.09・上限 2,043,605）:
    //
    //   斬撃(100)      216,036 → 3.10倍  上限に届かない
    //   黄昏(520)      727,867 → 2.84倍  **上限を超えて削られた**
    //
    // 威力を足すだけでは、育つほど利が減って害だけが残る。
    // cap_break で上限そのものを上げれば、一撃の重さがそのまま届く。
    // 「動かぬことを選んだ者の一撃は、常の理を超える」という像とも合う。
    //
    // ignoreCap（減衰を通さない）は破壊者の「終焉の一撃」だけが持つ固有性なので、
    // こちらへ配らない。押し上げるに留める。
    effects: [
      { kind: 'turn_debt', value: 1 },
      { kind: 'always_crit', value: 1 },
      { kind: 'always_power', value: 0.80 },
      { kind: 'cap_break', value: 2.00 },
    ],
  },
};

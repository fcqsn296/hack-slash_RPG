// 異相 (§22)
//
// ── 何のためにあるか ──
// 既存のフィールドに条件を重ねて、**同じ場所を別の戦いにする**もの。
// 新しい場所を作らない。増えるのは「どう組むか」の選択肢だけ。
//
// ── なぜ新フィールドではなく異相なのか ──
// ロードマップは「新フィールド・仲間の大量追加」を保留していて、
// 再開条件を **「既存12フィールド・60人を組み替える目的が決まる」** としている。
// 仲間は60人いるのに、最強の4人を組めばどこでも通るので、残りに出番が無い。
// 異相は「ここではその4人が通らない」を作る装置で、まさにその目的にあたる。
//
// ── 難度を上げる装置ではない ──
// **ここを外すと行き止まりに入る。** 終盤フィールドの難度を上げる案は
// 依頼書 §8 が既に否定している——オートで勝てない難度にすると、
// 周回する人は「オートで100%回せる手前のフィールド」へ移るだけ。
//
// 異相が要求するのは強さではなく **組み替え**。
// 火力を足しても通らないが、連れて行く相手を変えれば通る。
// だから元のフィールドの周回しやすさは一切変えない（選ばなければ従来どおり）。
// 相を選んだときだけ、難化の対価として報酬が上乗せされる（下の節）。
//
// ── 効き方は「属性の否定」を借りている ──
// 闘技場の elementNull (§17) と同じ位置で、同じように最後に均す。
// 適応・極意・貫通・双極・心得・耐性が、その属性についてはまとめて意味を失う。
// **適応2を抜け道にしない**のが要点で、そうしないと万能型が素通りして
// 「組み替える理由」が消える。
//
// ── 難しいのに実入りが同じなら、誰も選ばない ──
// **当初「報酬は変えない」で作っていたが、これは設計の誤りだった。**
// 依頼書 §8 の論理をそのまま当てれば、難しくて実入りが同じ選択肢は
// 選ばれないだけで、置いてあることに意味がなくなる。
//
// ── 校正は勝率ではなくラウンド数で行う ──
// **ここを間違えると、ビルドが強くなるほど上乗せが過大になる。**
//
// 最初は「1ラウンドあたりの期待ゴールド（負けた回を含む）」で校正した。
// もっともらしいが、負け分を報酬で埋める形になっている。検証用の土台は
// 実セーブより弱いので（装備セットが組めない）、その弱さのぶんを払うと
// 実プレイのビルドには過大に払うことになる。
// しかも上乗せが「弱いほど大きい」という向きになり、逆立ちしている。
//
// 負けはビルドで解く側の問題。報酬で埋めるものではない。
// だから**勝った回のラウンド数**だけを見る。
//
// ⚠ **平均のラウンド数を使わないこと。** 負けた回は速く全滅するので
// 平均に混ぜると周回のラウンドを過小に見積もる。実際に一度間違えた——
// あまねく相は平均 7.55R だが、勝った回だけなら 9.30R。
// 倍率が 1.65 と 2.00 のあいだでずれる。
//
// ラウンド数は60試行で安定する（勝率は10試行だと20〜30ポイント揺れた）。
//
// 採った規則: **要求された組み替えをすれば、1ラウンドあたり素の約1.3倍**。
// 相ごとの倍率の差は好みでなく実測のラウンド比から出る
// （終わりなき回廊・Lv255・4人・60試行、素は R 6.00 で勝率100%）。
//
//   相                        勝ちのR   比     rewardMult
//   闇/光を拒む               6.00      1.00   1.30
//   先を取る                  6.07      1.01   1.30
//   弱きを選ぶ(庇う役)         6.02      1.00   1.30
//   あまねく(全員 軽減+25%)    9.30      1.55   2.00
//   硬きを試す(受け役 +55%)    9.52      1.59   2.00
//
// 宝箱にも同じ倍率をかける。**一度半分にして、測って戻した。**
// 1ラウンドあたりの宝箱が硬きを試す相で 0.99 倍（つまり増えていない）になり、
// 半分にした上乗せが、増えたラウンドと勝率の損に食われて消えていた。
// 終盤の実入りの主役は装備の売却益なので、宝箱が増えないと上乗せが薄まる。
//
// ── 全体攻撃の相は、敵の倍率では調整できない ──
// あまねく相の勝率を上げようとして敵の倍率を下げても、効率は上がらない。
//   ×2   勝率33% / R 3.6     ×1.8 勝率37% / R 3.6
//   ×1.6 勝率45% / R 4.7     ×1.4 勝率50% / R 6.1
// 全員が傷むので耐久と回復に手番が食われ、**勝率を上げるとラウンドが伸びる**。
